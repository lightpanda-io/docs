// Generate the JavaScript SDK reference page from the lightpanda npm package.
//
// This script writes src/content/reference/javascript.mdx from the JSON that
// TypeDoc produces for the package (`typedoc --json`, run in a lightpanda-js
// checkout with its own typedoc.json), emitting one MDX section per public
// class, method, property, function, option type and error, with the
// signatures and JSDoc shipped in the code. Emitting MDX instead of TypeDoc's
// own HTML keeps the page inside the Nextra site: sidebar, search, dark mode
// and deep links all work as on any other page.
//
// Run it the way the javascript-reference workflow does daily:
//
//   git clone https://github.com/lightpanda-io/lightpanda-js /tmp/lightpanda-js
//   (cd /tmp/lightpanda-js && npm ci --ignore-scripts && npx typedoc --json /tmp/api.json)
//   node scripts/generate-javascript-reference.mjs --json /tmp/api.json
//
// The output is deterministic for a given package and TypeDoc version, so the
// workflow can detect changes with `git status`.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEFAULT_OUT = join(ROOT, 'src', 'content', 'reference', 'javascript.mdx')

const FRONTMATTER = `---
title: JavaScript SDK
description: Reference of every public class, method, property, option and error in the lightpanda npm package, generated from the signatures and JSDoc shipped in the code.
---`

const BANNER =
  '{/* Generated by scripts/generate-javascript-reference.mjs from lightpanda-js main. ' +
  'Do not edit; rerun the script or wait for the javascript-reference workflow. */}'

const INTRO =
  'Every public class, method, property, option and error of the ' +
  '[`lightpanda` npm package](https://www.npmjs.com/package/lightpanda), with the signatures ' +
  'and JSDoc shipped in the code. See the ' +
  '[package README](https://github.com/lightpanda-io/lightpanda-js#readme) for a practical ' +
  'walkthrough. The package is ESM with TypeScript declarations; every type named below is ' +
  "exported from `'lightpanda'`."

const CONVENTIONS = [
  "Browser actions are methods on [`Session`](#session), named after the browser's own " +
    "action names, each taking one options object with the action's arguments: " +
    "`page.waitForSelector({ selector: '.done' })`. The arguments of each method are listed " +
    'under it.',
  'Where a method accepts both `selector` and `backendNodeId`, pass one of the two. ' +
    '`selector` is preferred for reproducibility and wins when both are given; ' +
    '`backendNodeId` takes the values returned by [`tree`](#session-tree), ' +
    '[`links`](#session-links) or [`findElement`](#session-find-element).',
]

// Fixed paragraphs shown under a heading, after its JSDoc.
const NOTES = {
  Session:
    '[`call`](#session-call) is the escape hatch that takes the action and argument names ' +
    'exactly as the browser declares them. A failed action rejects with ' +
    '[`ToolError`](#toolerror).',
}

// Page order for the known exports. Anything exported but not listed here is
// appended to its group, so a new export is never silently left out.
const CLASS_ORDER = ['Browser', 'Session', 'CDPServer', 'BiDiServer']
const FUNCTION_ORDER = ['fetch', 'runScript', 'findBinary', 'bundledBrowserVersion']
const TYPE_ORDER = [
  'BrowserFlags',
  'LaunchOptions',
  'ProcessOptions',
  'FetchOptions',
  'FetchDump',
  'RunOptions',
  'ServeOptions',
  'ToolSpec',
]
const ERROR_ORDER = [
  'LightpandaError',
  'ProcessError',
  'RunError',
  'ScriptError',
  'ProtocolError',
  'ToolError',
]

const KIND = {
  function: 64,
  class: 128,
  interface: 256,
  constructor: 512,
  property: 1024,
  method: 2048,
  accessor: 262144,
  typeAlias: 2097152,
}

// Tool argument interfaces are shown under the Session method that takes them.
const ARGS_RE = /^[A-Z]\w*Args$/
const LINK_RE = /\]\(#([a-z0-9-]+)\)/g
const FENCE_RE = /^\s*```/

// Anchors match the Python page: a top-level name lowercased (`#toolerror`,
// `#cdpserver`), a member kebab-cased after it (`#session-find-element`).
const kebab = name =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()
const slug = (name, member) =>
  member ? `${name.toLowerCase()}-${kebab(member)}` : name.toLowerCase()

class Page {
  constructor() {
    this.lines = []
    this.ids = new Set()
  }

  heading(level, text, anchor) {
    if (this.ids.has(anchor)) throw new Error(`duplicate heading id: ${anchor}`)
    this.ids.add(anchor)
    this.lines.push(`${'#'.repeat(level)} ${text} [#${anchor}]`, '')
  }

  para(text) {
    if (text?.trim()) this.lines.push(text.trimEnd(), '')
  }

  fence(code, lang = 'ts') {
    this.lines.push(`\`\`\`${lang}`, code.trimEnd(), '```', '')
  }

  list(items) {
    if (items.length > 0) this.lines.push(...items, '')
  }

  text() {
    const text = `${this.lines.join('\n').trimEnd()}\n`
    const missing = [...new Set([...text.matchAll(LINK_RE)].map(m => m[1]))]
      .filter(id => !this.ids.has(id))
      .sort()
    if (missing.length > 0) throw new Error(`links to missing heading ids: ${missing.join(', ')}`)
    return text
  }
}

// --- types ------------------------------------------------------------------

const PRECEDENCE = { union: 1, intersection: 2 }

function typeString(type, parent = 0) {
  if (!type) return 'unknown'
  const wrap = (text, own) => (own < parent ? `(${text})` : text)
  switch (type.type) {
    case 'intrinsic':
      return type.name
    case 'literal':
      return type.value === null ? 'null' : JSON.stringify(type.value).replaceAll('"', "'")
    case 'reference': {
      // `Buffer` carries a defaulted type argument nobody writes.
      if (type.name === 'Buffer') return 'Buffer'
      const args = type.typeArguments?.map(t => typeString(t)).join(', ')
      return args ? `${type.name}<${args}>` : type.name
    }
    case 'array':
      return `${typeString(type.elementType, 3)}[]`
    case 'union':
      return wrap(type.types.map(t => typeString(t, PRECEDENCE.union)).join(' | '), 1)
    case 'intersection':
      return wrap(type.types.map(t => typeString(t, PRECEDENCE.intersection)).join(' & '), 2)
    case 'tuple':
      return `[${(type.elements ?? []).map(t => typeString(t)).join(', ')}]`
    case 'namedTupleMember':
      return `${type.name}${type.isOptional ? '?' : ''}: ${typeString(type.element)}`
    case 'typeOperator':
      return `${type.operator} ${typeString(type.target, 3)}`
    case 'query':
      return `typeof ${typeString(type.queryType)}`
    case 'indexedAccess':
      return `${typeString(type.objectType, 3)}[${typeString(type.indexType)}]`
    case 'reflection':
      return reflectionString(type.declaration)
    default:
      throw new Error(`unhandled TypeDoc type: ${type.type}`)
  }
}

function reflectionString(decl) {
  if (decl.signatures?.length) {
    const sig = decl.signatures[0]
    return `(${paramsString(sig)}) => ${typeString(sig.type)}`
  }
  const members = [
    ...(decl.indexSignatures ?? []).map(
      s =>
        `[${s.parameters.map(p => `${p.name}: ${typeString(p.type)}`).join(', ')}]: ${typeString(s.type)}`,
    ),
    ...(decl.children ?? []).map(
      c => `${c.name}${c.flags.isOptional ? '?' : ''}: ${typeString(c.type)}`,
    ),
  ]
  return members.length ? `{ ${members.join('; ')} }` : '{}'
}

function paramsString(sig) {
  return (sig.parameters ?? [])
    .map(
      p =>
        `${p.flags.isRest ? '...' : ''}${p.name}${p.flags.isOptional ? '?' : ''}: ${typeString(p.type)}`,
    )
    .join(', ')
}

// --- comments -----------------------------------------------------------------

function escapeProse(text) {
  return text.replaceAll('<', '&lt;').replaceAll('{', '\\{').replaceAll('}', '\\}')
}

// Renders TypeDoc comment parts as MDX: prose escaped, code spans kept (and
// linked when they name something on the page), fenced code kept verbatim.
function renderParts(parts, links) {
  let out = ''
  for (const part of parts ?? []) {
    if (part.kind === 'text') {
      out += escapeProse(part.text)
    } else if (part.kind === 'code') {
      if (part.text.startsWith('```')) {
        out += part.text
      } else {
        const inner = part.text.replace(/^`+|`+$/g, '')
        // `close()` names the method of the class being rendered; a bare
        // `host` is as likely an option as the property, so only calls and
        // qualified or top-level names link.
        const target = inner.endsWith('()')
          ? links.get(inner.slice(0, -2))
          : links.get(inner) && !links.members?.has(inner)
            ? links.get(inner)
            : undefined
        out += target ? `[${part.text}](#${target})` : part.text
      }
    } else if (part.kind === 'inline-tag') {
      const name = part.text.trim()
      const target =
        links.get(typeof part.target === 'number' ? idName(part.target) : name) ?? links.get(name)
      out += target ? `[\`${name}\`](#${target})` : `\`${name}\``
    }
  }
  return out.trim()
}

let reflectionsById = new Map()
const idName = id => {
  const r = reflectionsById.get(id)
  if (!r) return undefined
  return r.parentName ? `${r.parentName}.${r.name}` : r.name
}

function summary(reflection, links) {
  return renderParts(reflection?.comment?.summary, links)
}

// For list items: one line, whatever the JSDoc wrapping.
const oneLine = text => text.replace(/\s*\n\s*/g, ' ')

function blockTag(reflection, tag, links) {
  const found = reflection?.comment?.blockTags?.find(t => t.tag === tag)
  return found ? renderParts(found.content, links) : ''
}

// --- members ------------------------------------------------------------------

const isDispose = m => m.name === '[asyncDispose]'

function signatureCode(name, sig, { isStatic = false, prefix = '' } = {}) {
  const returns = sig.type ? `: ${typeString(sig.type)}` : ''
  return `${prefix}${isStatic ? 'static ' : ''}${name}(${paramsString(sig)})${returns}`
}

function referenceTarget(type, links) {
  if (type?.type !== 'reference') return undefined
  return links.get(type.name)
}

// "- **name** ([`Type`](#type)): comment" for the parameters worth a line.
function parameterItems(sig, links) {
  const items = []
  for (const param of sig.parameters ?? []) {
    const doc = summary(param, links)
    const target = referenceTarget(param.type, links)
    if (!doc && !target) continue
    const type = target ? ` ([\`${param.type.name}\`](#${target}))` : ''
    items.push(`- **${param.name}**${type}${doc ? `: ${oneLine(doc)}` : ''}`)
  }
  return items
}

function propertyItems(children, links) {
  return (children ?? [])
    .filter(c => c.kind === KIND.property)
    .map(c => {
      const doc = oneLine(summary(c, links))
      const optional = c.flags.isOptional ? '?' : ''
      return `- \`${c.name}${optional}: ${typeString(c.type)}\`${doc ? `: ${doc}` : ''}`
    })
}

function emitSignatureDocs(page, sig, links) {
  page.para(summary(sig, links))
  const params = parameterItems(sig, links)
  if (params.length) {
    page.lines.push('**Parameters:**', '')
    page.list(params)
  }
  const returns = blockTag(sig, '@returns', links)
  if (returns) page.para(`**Returns:** ${returns}`)
}

function emitArgs(page, sig, argsById) {
  const param = sig.parameters?.[0]
  const args = param?.type?.type === 'reference' ? argsById.get(param.type.target) : undefined
  if (!args) return
  const items = propertyItems(args.children, new Map())
  page.para(items.length ? `**Arguments** (\`${args.name}\`):` : 'Takes no arguments.')
  page.list(items)
}

function emitMember(page, cls, member, links, argsById) {
  page.heading(3, `${cls.name}.${member.name}`, slug(cls.name, member.name))
  if (member.kind === KIND.accessor) {
    const getter = member.getSignature
    page.fence(`${member.name}: ${typeString(getter?.type)}`)
    page.para(`*Property.* ${summary(getter, links)}`.trimEnd())
    return
  }
  if (member.kind === KIND.property) {
    page.fence(`${member.name}: ${typeString(member.type)}`)
    page.para(summary(member, links))
    return
  }
  const sigs = member.signatures ?? []
  page.fence(sigs.map(sig => signatureCode(member.name, sig, member.flags)).join('\n'))
  for (const sig of sigs) {
    emitSignatureDocs(page, sig, links)
    emitArgs(page, sig, argsById)
  }
}

function listedMembers(cls) {
  return (cls.children ?? []).filter(
    m => m.kind !== KIND.constructor && !isDispose(m) && !m.flags.isPrivate && !m.flags.isProtected,
  )
}

// Statics (the `launch` factories) first, then the rest in source order.
function orderedMembers(cls) {
  const members = listedMembers(cls)
  return [...members.filter(m => m.flags.isStatic), ...members.filter(m => !m.flags.isStatic)]
}

function emitClass(page, cls, links, argsById) {
  page.heading(2, cls.name, slug(cls.name))
  page.para(summary(cls, links))
  page.para(NOTES[cls.name])
  // Internal bases (SessionMethods, ServeProcess) are not on the page; their
  // members are listed as the class's own.
  const base = cls.extendedTypes?.map(t => typeString(t)).filter(n => links.has(n))
  page.fence(`class ${cls.name}${base?.length ? ` extends ${base.join(', ')}` : ''}`)
  if ((cls.children ?? []).some(isDispose)) {
    page.para('Supports `await using`, which calls `close()` on scope exit.')
  }
  for (const member of orderedMembers(cls)) emitMember(page, cls, member, links, argsById)
}

function emitFunction(page, fn, links) {
  page.heading(2, fn.name, slug(fn.name))
  const sigs = fn.signatures ?? []
  page.fence(sigs.map(sig => signatureCode(fn.name, sig, { prefix: 'function ' })).join('\n'))
  // Overloads narrow the return type per argument; the first one carries the
  // function's documentation.
  if (sigs.length) emitSignatureDocs(page, sigs[0], links)
}

function emitType(page, type, links) {
  page.heading(3, type.name, slug(type.name))
  if (type.kind === KIND.interface) {
    page.fence(`interface ${type.name}`)
    page.para(summary(type, links))
    page.list(propertyItems(type.children, links))
  } else {
    page.fence(`type ${type.name} = ${typeString(type.type)}`)
    page.para(summary(type, links))
  }
}

function emitError(page, cls, links) {
  page.heading(3, cls.name, slug(cls.name))
  const base = cls.extendedTypes?.map(t => typeString(t)) ?? []
  page.fence(`class ${cls.name}${base.length ? ` extends ${base.join(', ')}` : ''}`)
  page.para(summary(cls, links))
  const own = (cls.children ?? []).filter(c => c.kind === KIND.property && !c.inheritedFrom)
  page.list(propertyItems(own, links))
}

// --- page ---------------------------------------------------------------------

function ordered(items, order) {
  const known = order.map(name => items.find(i => i.name === name)).filter(Boolean)
  const rest = items
    .filter(i => !order.includes(i.name))
    .sort((a, b) => a.name.localeCompare(b.name))
  return [...known, ...rest]
}

function indexReflections(project) {
  reflectionsById = new Map()
  const visit = (r, parentName) => {
    reflectionsById.set(r.id, { name: r.name, parentName })
    for (const child of r.children ?? []) visit(child, r.kind === KIND.class ? r.name : undefined)
  }
  for (const child of project.children ?? []) visit(child)
}

function collectLinks(classes, functions, types, errors) {
  const links = new Map()
  links.members = new Set()
  for (const item of [...classes, ...functions, ...types, ...errors])
    links.set(item.name, slug(item.name))
  for (const cls of classes) {
    for (const member of listedMembers(cls)) {
      links.set(`${cls.name}.${member.name}`, slug(cls.name, member.name))
    }
  }
  return links
}

// Bare member names (`close()`) resolve against the class being rendered.
function classLinks(links, cls) {
  const scoped = new Map(links)
  scoped.members = new Set()
  for (const member of listedMembers(cls)) {
    if (!scoped.has(member.name)) {
      scoped.set(member.name, slug(cls.name, member.name))
      scoped.members.add(member.name)
    }
  }
  return scoped
}

function isError(cls, byName) {
  for (let c = cls; c; ) {
    if (c.name === 'LightpandaError') return true
    const base = c.extendedTypes?.[0]
    c = base ? byName.get(base.name) : undefined
    if (!c && base?.name === 'Error') return true
  }
  return false
}

function generate(project) {
  indexReflections(project)
  const children = project.children ?? []
  const byName = new Map(children.map(c => [c.name, c]))
  const allClasses = children.filter(c => c.kind === KIND.class)
  const errors = ordered(
    allClasses.filter(c => isError(c, byName)),
    ERROR_ORDER,
  )
  const classes = ordered(
    allClasses.filter(c => !errors.includes(c)),
    CLASS_ORDER,
  )
  const functions = ordered(
    children.filter(c => c.kind === KIND.function),
    FUNCTION_ORDER,
  )
  const argsInterfaces = children.filter(c => c.kind === KIND.interface && ARGS_RE.test(c.name))
  const argsById = new Map(argsInterfaces.map(a => [a.id, a]))
  const types = ordered(
    children.filter(
      c => (c.kind === KIND.interface || c.kind === KIND.typeAlias) && !argsInterfaces.includes(c),
    ),
    TYPE_ORDER,
  )
  const links = collectLinks(classes, functions, types, errors)

  const page = new Page()
  page.lines.push(FRONTMATTER, BANNER, '', '# JavaScript SDK', '')
  page.para(INTRO)
  for (const paragraph of CONVENTIONS) page.para(paragraph)

  for (const cls of classes) emitClass(page, cls, classLinks(links, cls), argsById)
  for (const fn of functions) emitFunction(page, fn, links)

  if (types.length) {
    page.heading(2, 'Options and types', 'options-and-types')
    for (const type of types) emitType(page, type, links)
  }
  if (errors.length) {
    page.heading(2, 'Errors', 'errors')
    for (const cls of errors) emitError(page, cls, classLinks(links, cls))
  }

  return rewriteFences(page.text())
}

// Fenced code inside JSDoc arrives as one code part; make sure it starts on
// its own line so MDX sees a fence, not inline backticks.
function rewriteFences(text) {
  const out = []
  for (const line of text.split('\n')) {
    const at = line.indexOf('```')
    if (at > 0 && !FENCE_RE.test(line)) {
      out.push(line.slice(0, at).trimEnd(), '', line.slice(at))
    } else {
      out.push(line)
    }
  }
  return out.join('\n')
}

function main() {
  const { values } = parseArgs({
    options: {
      json: { type: 'string' },
      out: { type: 'string', default: DEFAULT_OUT },
    },
  })
  if (!values.json) {
    console.error(
      'usage: generate-javascript-reference.mjs --json <typedoc.json> [--out <file.mdx>]',
    )
    process.exit(2)
  }
  const project = JSON.parse(readFileSync(values.json, 'utf8'))
  mkdirSync(dirname(values.out), { recursive: true })
  writeFileSync(values.out, generate(project))
  const shown = relative(ROOT, values.out)
  console.log(`wrote ${shown.startsWith('..') ? values.out : shown}`)
}

main()
